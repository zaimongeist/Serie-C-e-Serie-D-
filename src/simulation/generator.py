def default_home_advantage(gironi: Sequence[Girone] | None = None) -> dict[Girone, float]:
    """True home advantage per competition: :data:`DEFAULT_HOME_ADVANTAGE` by code, :data:`FALLBACK_HOME_ADVANTAGE` otherwise.

    Every configured competition by default (so :class:`TrueParams.gamma` always
    covers the whole :class:`Girone` enum), or only ``gironi``.
    """
    targets = tuple(Girone) if gironi is None else tuple(Girone.parse(g) for g in gironi)
    return {g: float(DEFAULT_HOME_ADVANTAGE.get(g.value, FALLBACK_HOME_ADVANTAGE)) for g in targets}


# --------------------------------------------------------------------------- math
def _tau(x: np.ndarray, y: np.ndarray, lam: float, mu: float, rho: float) -> np.ndarray:
    out = np.ones_like(x, dtype=float)
    out = np.where((x == 0) & (y == 0), 1.0 - lam * mu * rho, out)
    out = np.where((x == 0) & (y == 1), 1.0 + lam * rho, out)
    out = np.where((x == 1) & (y == 0), 1.0 + mu * rho, out)
    out = np.where((x == 1) & (y == 1), 1.0 - rho, out)
    return out


def dixon_coles_matrix(lam: float, mu: float, rho: float, max_goals: int = MAX_GOALS) -> np.ndarray:
    """Joint pmf P(X=x, Y=y) on a (max_goals+1)x(max_goals+1) grid, renormalised."""
    from scipy.stats import poisson

    xs = np.arange(max_goals + 1)
    px = poisson.pmf(xs, lam)
    py = poisson.pmf(xs, mu)
    grid = np.outer(px, py)
    X, Y = np.meshgrid(xs, xs, indexing="ij")
    grid = grid * np.clip(_tau(X, Y, lam, mu, rho), 1e-12, None)
    return grid / grid.sum()


def market_probabilities(matrix: np.ndarray) -> dict[Market, dict[str, float]]:
    """Derive 1X2 / O-U / GG-NG probabilities from a joint score matrix."""
    n = matrix.shape[0]
    X, Y = np.meshgrid(np.arange(n), np.arange(n), indexing="ij")
    total = X + Y
    out: dict[Market, dict[str, float]] = {
        Market.MATCH_ODDS: {
            "1": float(matrix[X > Y].sum()),
            "X": float(np.trace(matrix)),
            "2": float(matrix[X < Y].sum()),
        },
        Market.BTTS: {
            "GG": float(matrix[(X > 0) & (Y > 0)].sum()),
            "NG": float(matrix[(X == 0) | (Y == 0)].sum()),
        },
    }
    for market, line in ((Market.OVER_UNDER_15, 1.5), (Market.OVER_UNDER_25, 2.5), (Market.OVER_UNDER_35, 3.5)):
        over = float(matrix[total > line].sum())
        out[market] = {f"Over {line}": over, f"Under {line}": 1.0 - over}
    return out


# ------------------------------------------------------------------- calendar
def season_start_date(label: str) -> date:
    """Kick-off Sunday of a season: the first Sunday on or after 20 August of its first year.

    Reproduces the real Serie C kick-offs of the simulated seasons (25 Aug 2024,
    24 Aug 2025, 23 Aug 2026).
    """
    first, _ = season_bounds(label)
    anchor = date(first.year, 8, 20)
    return anchor + timedelta(days=(6 - anchor.weekday()) % 7)


def previous_seasons(label: str, n: int) -> tuple[str, ...]:
    """The ``n`` seasons before ``label``, oldest first: ``('2024/25', '2025/26')`` for ``'2026/27'`` and ``n=2``.

    ``label`` accepts every spelling :func:`season_bounds` does (``'2026_27'``
    works); ``n <= 0`` yields an empty tuple.
    """
    first, _ = season_bounds(label)
    return tuple(season_of(date(first.year - k, first.month, 1)) for k in range(max(int(n), 0), 0, -1))


def _registry_start_date(registry: TeamRegistry) -> date:
    """Kick-off of the registry season (:func:`season_start_date`), :data:`SEASON_2026_27_START` when the label is not a season."""
    try:
        return season_start_date(registry.season_label)
    except ValueError:
        return SEASON_2026_27_START


def history_seasons_for(registry: TeamRegistry, n: int) -> tuple[str, ...]:
    """Labels of the ``n`` synthetic past seasons of ``registry``, oldest first.

    The ``n`` seasons before the registry season (:func:`previous_seasons`:
    ``('2024/25', '2025/26')`` for the 2026/27 registry and ``n=2``,
    ``('2023/24', '2024/25')`` for a 2025/26 one); when the registry label is not
    a season (``'sim'``) the last ``n`` of :data:`HISTORY_SEASONS`. Shared by
    :func:`simulate_history`, ``main.py`` and the dashboard so every surface
    agrees on which seasons are history.
    """
    try:
        return previous_seasons(registry.season_label, n)
    except ValueError:
        return HISTORY_SEASONS[max(len(HISTORY_SEASONS) - int(n), 0) :] if int(n) > 0 else ()


# ------------------------------------------------------------------- parameters
@dataclass(frozen=True)
class TrueParams:
    """Ground-truth parameters used to generate a league."""

    alpha: Mapping[str, float]  # attack, sum == 0 within each girone
    beta: Mapping[str, float]  # defence (higher = concedes less)
    gamma: Mapping[Girone, float]  # home advantage per girone
    rho: float
    xi: float = 0.0  # time-decay used for generation (0 = stationary)

    def rates(self, home: str, away: str, girone: Girone) -> tuple[float, float]:
        lam = float(np.exp(self.alpha[home] - self.beta[away] + self.gamma[girone]))
        mu = float(np.exp(self.alpha[away] - self.beta[home]))
        return lam, mu

    def extended(self, alpha: Mapping[str, float], beta: Mapping[str, float]) -> "TrueParams":
        """Copy with extra teams (existing teams keep their strengths)."""
        return TrueParams(
            alpha={**alpha, **dict(self.alpha)},
            beta={**beta, **dict(self.beta)},
            gamma=dict(self.gamma),
            rho=self.rho,
            xi=self.xi,
        )


def sample_true_params(
    registry: TeamRegistry,
    rng: np.random.Generator,
    *,
    sigma_alpha: float = 0.28,
    sigma_beta: float = 0.22,
    gamma: Mapping[Girone, float] | None = None,
    rho: float = -0.06,
) -> TrueParams:
    alpha: dict[str, float] = {}
    beta: dict[str, float] = {}
    for g in registry.gironi:  # only the competitions that have teams (empty Serie D gironi contribute nothing)
        teams = registry.teams_by_girone[g]
        a = rng.normal(0.0, sigma_alpha, len(teams))
        a -= a.mean()  # identifiability: sum alpha = 0 per girone
        b = rng.normal(0.0, sigma_beta, len(teams))
        for t, ai, bi in zip(teams, a, b):
            alpha[t] = float(ai)
            beta[t] = float(bi)
    if gamma is None:
        gamma = default_home_advantage()
    return TrueParams(alpha=alpha, beta=beta, gamma=dict(gamma), rho=rho)


# -------------------------------------------------------------------- schedule
def round_robin(teams: Sequence[str], *, double: bool = True) -> list[list[tuple[str, str]]]:
    """Circle-method round robin. Returns rounds of (home, away) pairs."""
    teams = list(teams)
    if len(teams) % 2:
        teams.append("__BYE__")
    n = len(teams)
    rounds: list[list[tuple[str, str]]] = []
    order = teams[:]
    for r in range(n - 1):
        pairs: list[tuple[str, str]] = []
        for i in range(n // 2):
            a, b = order[i], order[n - 1 - i]
            if "__BYE__" in (a, b):
                continue
            pairs.append((a, b) if (r + i) % 2 == 0 else (b, a))
        rounds.append(pairs)
        order = [order[0]] + [order[-1]] + order[1:-1]
    if double:
        rounds += [[(b, a) for a, b in rnd] for rnd in rounds]
    return rounds


# ------------------------------------------------------------------- generator
@dataclass
class SimulatedLeague:
    """A simulated dataset: played matches (canonical frame), fixtures and synthetic odds.

    ``registry`` is the registry of the *current* perimeter; for a history
    produced by :func:`simulate_history`, ``seasons`` lists the simulated season
    labels and ``season_registries`` the composition actually used in each of
    them (the current registry with swaps and moves applied).
    """

    registry: TeamRegistry
    true_params: TrueParams
    matches: pd.DataFrame
    fixtures: list[Fixture]
    odds: list[OddsQuote] = field(default_factory=list)
    seasons: tuple[str, ...] = ()
    season_registries: dict[str, TeamRegistry] = field(default_factory=dict)

    @property
    def n_matches(self) -> int:
        return int(len(self.matches))

    @property
    def teams(self) -> tuple[str, ...]:
        """Every team that appears in ``matches`` (current and historical), sorted."""
        if self.matches.empty:
            return ()
        return tuple(sorted(set(self.matches["home_team"].astype(str)) | set(self.matches["away_team"].astype(str))))


def _simulate_stats(rng: np.random.Generator, lam: float, goals: int) -> tuple[float, float, float, float]:
    """xG, shots, shots on target, corners roughly consistent with the rate."""
    xg = float(lam * rng.lognormal(0.0, 0.35))
    xg = max(xg, 0.05 + 0.4 * goals * rng.uniform(0.3, 0.9))
    shots = int(max(goals, rng.poisson(3.0 + 7.5 * xg)))
    sot = int(np.clip(rng.binomial(shots, 0.36), goals, shots))
    corners = int(rng.poisson(4.5 + 1.2 * xg))
    return round(xg, 2), float(shots), float(sot), float(corners)


def _played_rounds_as_of(as_of: date, start_date: date, days_between_rounds: int, total_rounds: int) -> int:
    """Rounds dated strictly before ``as_of`` (capped at ``total_rounds``, never negative)."""
    elapsed = (as_of - start_date).days
    if elapsed <= 0:
        return 0
    return min(total_rounds, int(math.ceil(elapsed / days_between_rounds)))


def simulate_league(
    *,
    seed: int = 7,
    registry: TeamRegistry | None = None,
    teams_by_girone: Mapping[str, Sequence[str]] | None = None,
    n_rounds: int | None = None,
    start_date: date | None = None,
    days_between_rounds: int = 7,
    true_params: TrueParams | None = None,
    with_odds: bool = True,
    bookmaker_margin: float = 0.06,
    bookmaker_noise: float = 0.04,
    as_of: date | None = None,
    match_id_prefix: str = "SIM",
) -> SimulatedLeague:
    """Generate a full (or truncated) season with known parameters.

    By default the real **2026/27** Serie C composition (:func:`load_registry`) is
    used on a weekly calendar starting on :data:`SEASON_2026_27_START`. With
    ``start_date=None`` the calendar follows the registry season
    (:func:`season_start_date` of ``registry.season_label``: 24 August 2025 for
    a 2025/26 registry), so the matches are always dated in the season the
    registry describes; a registry whose label is not a season (``'sim'``) uses
    the 2026/27 calendar.

    How many rounds are played:

    * ``n_rounds`` (explicit control) limits the number of *played* rounds; the
      following round becomes the fixture list;
    * otherwise ``as_of`` derives it from the calendar: rounds dated before
      ``as_of`` are played and the first round on/after ``as_of`` is the fixture
      list (empty when the season is over, no matches when it has not started);
    * with neither, every round but the last one is played, so there is always a
      fixture list.

    ``match_id_prefix`` lets several simulated seasons coexist in one frame with
    unique ids (``validate_matches_df`` keeps only the last duplicate id).
    """
    rng = np.random.default_rng(seed)
    if registry is None:
        registry = (
            TeamRegistry.from_teams("sim", teams_by_girone)
            if teams_by_girone is not None
            else load_registry()
        )
    params = true_params or sample_true_params(registry, rng)
    if start_date is None:
        start_date = _registry_start_date(registry)

    # only the competitions that have teams are simulated: the empty Serie D gironi of the shipped
    # registry (filled by the FootyStats auto-init) keep the default fallback league at Serie C + Serie B
    schedules = {g: round_robin(registry.teams_by_girone[g]) for g in registry.gironi}
    if not schedules:
        raise ValueError(f"registry {registry.season!r} has no teams in any competition: nothing to simulate")
    total_rounds = max(len(s) for s in schedules.values())
    if n_rounds is not None:
        played_rounds = max(0, min(int(n_rounds), total_rounds))
    elif as_of is not None:
        played_rounds = _played_rounds_as_of(as_of, start_date, days_between_rounds, total_rounds)
    else:
        played_rounds = total_rounds - 1

    records: list[MatchRecord] = []
    fixtures: list[Fixture] = []
    counter = 0
    for rnd in range(total_rounds):
        when = start_date + timedelta(days=rnd * days_between_rounds)
        for g, sched in schedules.items():
            if rnd >= len(sched):
                continue
            for home, away in sched[rnd]:
                counter += 1
                mid = f"{match_id_prefix}-{g.value}-{rnd + 1:02d}-{counter:04d}"
                if rnd >= played_rounds:
                    if rnd == played_rounds:
                        fixtures.append(Fixture(mid, when, rnd + 1, g, home, away))
                    continue
                lam, mu = params.rates(home, away, g)
                grid = dixon_coles_matrix(lam, mu, params.rho)
                idx = rng.choice(grid.size, p=grid.ravel())
                hg, ag = divmod(int(idx), grid.shape[1])
                hxg, hs, hst, hc = _simulate_stats(rng, lam, hg)
                axg, as_, ast, ac = _simulate_stats(rng, mu, ag)
                records.append(
                    MatchRecord(
                        match_id=mid,
                        date=when,
                        round=rnd + 1,
                        girone=g,
                        home_team=home,
                        away_team=away,
                        home_goals=hg,
                        away_goals=ag,
                        home_shots=hs,
                        away_shots=as_,
                        home_shots_target=hst,
                        away_shots_target=ast,
                        home_corners=hc,
                        away_corners=ac,
                        home_xg=hxg,
                        away_xg=axg,
                    )
                )
    league = SimulatedLeague(
        registry=registry,
        true_params=params,
        matches=matches_to_frame(records),
        fixtures=fixtures,
        seasons=(season_of(start_date),),
        season_registries={season_of(start_date): registry},
    )
    if with_odds and fixtures:
        league.odds = simulate_bookmaker_odds(league, rng, margin=bookmaker_margin, noise=bookmaker_noise)
    return league


def _season_composition(
    registry: TeamRegistry,
    label: str,
    rng: np.random.Generator,
    swap_per_girone: int,
) -> dict[Girone, tuple[str, ...]]:
    """Composition of one past season: the current registry with moves, absences and swaps applied.

    Every competition keeps its current size. Teams in :data:`HISTORICAL_MOVES`
    (when present in ``registry`` *and* when their destination competition is
    one the registry has: a Serie B move is skipped for a Serie-C-only registry)
    sit in the competition they played in that season and are never swapped out;
    teams in :data:`HISTORICAL_ABSENCES` are removed; then ``swap_per_girone`` of
    the remaining current teams of each competition are replaced by names from
    :data:`HISTORICAL_TEAMS` (a fresh permutation of the pool per season, so a
    club can appear in several seasons). When moves leave a competition over its
    size, extra current teams are dropped; under its size, extra historical
    teams fill it.

    The pool is size-safe: names of :data:`HISTORICAL_TEAMS` that are current
    teams of ``registry`` are left out (12 of them play Serie C 2025/26), then
    the registry's own ``historical_names`` (older season files merged with
    :meth:`TeamRegistry.with_historical_aliases`) are appended, and when even
    those run out synthetic clubs ``'Storica 01'``, ``'Storica 02'``, ... fill the
    gaps with a warning instead of raising, so every registry can be simulated.
    """
    comp: dict[Girone, list[str]] = {g: list(registry.teams_by_girone[g]) for g in registry.gironi}
    sizes = {g: len(teams) for g, teams in comp.items()}
    moved: set[str] = set()
    for team, target in HISTORICAL_MOVES.get(label, {}).items():
        source = next((g for g, teams in comp.items() if team in teams), None)
        if source is None or target not in comp:
            continue
        if source is not target:
            comp[source].remove(team)
            comp[target].append(team)
        moved.add(team)
    for team in HISTORICAL_ABSENCES.get(label, frozenset()):
        for teams in comp.values():
            if team in teams:
                teams.remove(team)
    pool = _historical_pool(registry, rng)
    n_synthetic = 0
    for g in Girone:
        if g not in comp:
            continue
        teams = comp[g]
        candidates = [t for t in teams if t not in moved]
        n_swap = min(max(int(swap_per_girone), 0), len(candidates))
        extra_out = max(0, len(teams) - n_swap - sizes[g])
        n_out = min(len(candidates), n_swap + extra_out)
        if n_out:
            for t in rng.choice(np.array(candidates, dtype=object), size=n_out, replace=False):
                teams.remove(str(t))
        need = sizes[g] - len(teams)
        if need > len(pool):
            missing = need - len(pool)
            pool.extend(f"{SYNTHETIC_HISTORICAL_PREFIX} {n_synthetic + i + 1:02d}" for i in range(missing))
            n_synthetic += missing
            log.warning(
                "historical pool exhausted, synthetic clubs added to the composition",
                extra={"season": label, "girone": g.value, "registry_season": registry.season_label, "synthetic": missing},
            )
        teams.extend(pool[:need])
        del pool[:need]
    return {g: tuple(teams) for g, teams in comp.items()}


def _historical_pool(registry: TeamRegistry, rng: np.random.Generator) -> list[str]:
    """Shuffled names available as historical opponents of ``registry``.

    :data:`HISTORICAL_TEAMS` minus the registry's current teams (one permutation
    drawn from ``rng``), followed by the registry's ``historical_names`` that are
    not already in the pool (a second permutation, drawn only when there are
    any, so the draws of a registry without history are unchanged).
    """
    current = set(registry.canonical_names)
    pool = [str(t) for t in rng.permutation(np.array(HISTORICAL_TEAMS, dtype=object)) if t not in current]
    extra = [str(t) for t in registry.historical_names if t not in current and t not in pool]
    if extra:
        pool.extend(str(t) for t in rng.permutation(np.array(extra, dtype=object)))
    return pool


def simulate_history(
    *,
    seed: int = 7,
    registry: TeamRegistry | None = None,
    seasons: Sequence[str] | None = None,
    swap_per_girone: int = 3,
    true_params: TrueParams | None = None,
    sigma_alpha: float = 0.28,
    sigma_beta: float = 0.22,
) -> SimulatedLeague:
    """Synthetic *past* seasons for the perimeter of ``registry`` (default: 2026/27).

    ``seasons`` defaults to the two seasons before the registry season
    (:func:`previous_seasons`: 2024/25 and 2025/26 for 2026/27, 2023/24 and
    2024/25 for a 2025/26 registry), so the history always precedes the current
    season whatever registry is used. Each season is a full double round robin
    on its real calendar (:func:`season_start_date`: 25 Aug 2024, 24 Aug 2025)
    whose composition is the current registry with ``swap_per_girone`` current
    teams per competition replaced by real former Serie C / Serie B clubs
    (:data:`HISTORICAL_TEAMS`, padded as described in the module docstring when
    the pool runs short), plus the moves of :data:`HISTORICAL_MOVES` (Inter U23
    in A, Atalanta U23 in C, Juventus Next Gen in B, Pescara / Spezia /
    Reggiana / Bari in Serie B, Arezzo / Ascoli / Benevento / Vicenza in their
    Serie C gironi, ... for 2025/26) and the absences of
    :data:`HISTORICAL_ABSENCES`. The same
    :class:`TrueParams` drive every season: ``true_params`` when given,
    otherwise the ones ``simulate_league(seed=seed, registry=registry)`` samples
    for the current season, extended with strengths for the whole historical
    pool drawn from the same distribution (``alpha ~ N(0, sigma_alpha)``,
    ``beta ~ N(0, sigma_beta)``), so the current season simulated with the same
    ``seed`` is consistent with its history. Historical names outside
    :data:`HISTORICAL_TEAMS` (registry history, synthetic clubs) get their
    strengths from the same distribution once the compositions are known.

    The result has no fixtures and no odds (history is only ever played);
    ``match_id`` values are prefixed per season (``HIST2425-A-01-0001``) so the
    seasons can be concatenated with the current one. Everything is seeded and
    deterministic.
    """
    rng = np.random.default_rng(seed)
    reg = registry if registry is not None else load_registry()
    base = true_params or sample_true_params(reg, rng, sigma_alpha=sigma_alpha, sigma_beta=sigma_beta)
    alpha_hist = {t: float(v) for t, v in zip(HISTORICAL_TEAMS, rng.normal(0.0, sigma_alpha, len(HISTORICAL_TEAMS)))}
    beta_hist = {t: float(v) for t, v in zip(HISTORICAL_TEAMS, rng.normal(0.0, sigma_beta, len(HISTORICAL_TEAMS)))}
    params = base.extended(alpha_hist, beta_hist)

    labels = tuple(sorted(str(s) for s in seasons)) if seasons is not None else history_seasons_for(reg, len(HISTORY_SEASONS))
    compositions = {label: _season_composition(reg, label, rng, swap_per_girone) for label in labels}
    unknown = sorted({t for comp in compositions.values() for teams in comp.values() for t in teams} - set(params.alpha))
    if unknown:  # names beyond HISTORICAL_TEAMS (registry history, synthetic clubs): same distribution
        params = params.extended(
            {t: float(v) for t, v in zip(unknown, rng.normal(0.0, sigma_alpha, len(unknown)))},
            {t: float(v) for t, v in zip(unknown, rng.normal(0.0, sigma_beta, len(unknown)))},
        )
    frames: list[pd.DataFrame] = []
    season_registries: dict[str, TeamRegistry] = {}
    for k, label in enumerate(labels):
        composition = compositions[label]
        season_registry = TeamRegistry.from_teams(label, {g.value: teams for g, teams in composition.items()})
        total_rounds = max(len(round_robin(teams)) for teams in composition.values())
        season_seed = int(np.random.SeedSequence([int(seed), k + 1]).generate_state(1)[0])
        first_year = season_bounds(label)[0].year
        league = simulate_league(
            seed=season_seed,
            registry=season_registry,
            n_rounds=total_rounds,
            start_date=season_start_date(label),
            true_params=params,
            with_odds=False,
            match_id_prefix=f"HIST{first_year % 100:02d}{(first_year + 1) % 100:02d}",
        )
        frames.append(league.matches)
        season_registries[label] = season_registry
        log.info(
            "simulated history season",
            extra={
                "season": label,
                "n_matches": int(len(league.matches)),
                "n_teams": season_registry.n_teams,
                "historical_teams": sorted(set(season_registry.canonical_names) - set(reg.canonical_names)),
            },
        )
    matches = matches_to_frame([]) if not frames else pd.concat(frames, ignore_index=True)
    if not matches.empty:
        matches = matches.sort_values(["date", "girone", "match_id"], kind="stable").reset_index(drop=True)
    else:
        matches = empty_matches_frame()
    return SimulatedLeague(
        registry=reg,
        true_params=params,
        matches=matches,
        fixtures=[],
        odds=[],
        seasons=labels,
        season_registries=season_registries,
    )


def simulate_bookmaker_odds(
    league: SimulatedLeague,
    rng: np.random.Generator | None = None,
    *,
    margin: float = 0.06,
    noise: float = 0.04,
    bookmaker: str = "SimBook",
    markets: Sequence[Market] = tuple(Market),
) -> list[OddsQuote]:
    """Bookmaker prices = true probability * multiplicative noise, then an
    over-round of ``margin`` is applied proportionally (sum implied = 1+margin).
    A noisy book is exactly what creates +EV spots for the value engine."""
    rng = rng or np.random.default_rng(0)
    quotes: list[OddsQuote] = []
    for fx in league.fixtures:
        lam, mu = league.true_params.rates(fx.home_team, fx.away_team, fx.girone)
        probs = market_probabilities(dixon_coles_matrix(lam, mu, league.true_params.rho))
        for market in markets:
            p = np.array([probs[market][s] for s in SELECTIONS[market]])
            p = p * rng.lognormal(0.0, noise, len(p))
            p = p / p.sum() * (1.0 + margin)
            quotes.append(
                OddsQuote(
                    match_id=fx.match_id,
                    bookmaker=bookmaker,
                    market=market,
                    odds={s: max(1.01, round(float(1.0 / pi), 2)) for s, pi in zip(SELECTIONS[market], p)},
                )
            )
    return quotes


def inject_regression_trap(
    matches: pd.DataFrame,
    team: str,
    *,
    window: int = 3,
    goals_against_total: int = 1,
    xga_total: float = 4.2,
) -> pd.DataFrame:
    """Rewrite ``team``'s last ``window`` matches so that it conceded at most
    ``goals_against_total`` goals in total while facing ``xga_total`` xG against.
    Returns a modified copy (used to showcase the REGRESSION_TRAP filter)."""
    df = matches.copy()
    mask = (df["home_team"] == team) | (df["away_team"] == team)
    idx = df.loc[mask].sort_values("date").index[-window:]
    if len(idx) < window:
        raise ValueError(f"{team} has fewer than {window} matches")
    ga_split = [goals_against_total] + [0] * (window - 1)
    xga_split = np.full(window, xga_total / window)
    for i, ga, xga in zip(idx, ga_split, xga_split):
        is_home = df.at[i, "home_team"] == team
        if is_home:
            df.at[i, "away_goals"] = int(ga)
            df.at[i, "away_xg"] = float(round(xga, 2))
            df.at[i, "away_shots"] = max(float(df.at[i, "away_shots"]) if pd.notna(df.at[i, "away_shots"]) else 0.0, 12.0)
            df.at[i, "away_shots_target"] = max(float(df.at[i, "away_shots_target"]) if pd.notna(df.at[i, "away_shots_target"]) else 0.0, 5.0)
        else:
            df.at[i, "home_goals"] = int(ga)
            df.at[i, "home_xg"] = float(round(xga, 2))
            df.at[i, "home_shots"] = max(float(df.at[i, "home_shots"]) if pd.notna(df.at[i, "home_shots"]) else 0.0, 12.0)
            df.at[i, "home_shots_target"] = max(float(df.at[i, "home_shots_target"]) if pd.notna(df.at[i, "home_shots_target"]) else 0.0, 5.0)
    return df


#: Composition of the 20-match console demo: 14 teams of the 2026/27 registry (6 + 4 + 4).
MINI_TEAMS: dict[str, tuple[str, ...]] = {
    "A": ("Pro Vercelli", "Cittadella", "Lecco", "Novara", "Trento", "Renate"),
    "B": ("Pescara", "Spezia", "Reggiana", "Perugia"),
    "C": ("Bari", "Salernitana", "Catania", "Crotone"),
}


def simulate_mini_dataset(seed: int = 42, n_matches: int = 20, *, season: str = DEFAULT_SEASON) -> SimulatedLeague:
    """Exactly ``n_matches`` played games across the three gironi (14 teams of the
    2026/27 perimeter, :data:`MINI_TEAMS`), with the following round as fixtures
    and simulated bookmaker odds. The registry carries the ``season`` label
    (2026/27 by default) so the demo can be fitted with ``registry=mini.registry``,
    and the calendar is that season's (:func:`season_start_date`).

    The mini dataset is a **fixed early-season snapshot**: the first ``n_matches``
    matches of the calendar (rounds 1-3 with the default 20) and the following
    round as fixtures, whatever today's date -- the 4-team gironi B and C only
    have six rounds, so the demo cannot follow the real calendar the way
    :func:`simulate_league` does with ``as_of``. Callers state this in their
    banners."""
    registry = TeamRegistry.from_teams(str(season).replace("_", "/"), MINI_TEAMS)
    league = simulate_league(seed=seed, registry=registry, n_rounds=10, with_odds=False)
    df = league.matches.sort_values(["date", "match_id"]).head(n_matches).reset_index(drop=True)
    last_round = int(df["round"].max())
    nxt = league.matches[league.matches["round"] == last_round + 1]
    fixtures = [
        Fixture(r.match_id, r.date.date(), int(r.round), Girone.parse(r.girone), r.home_team, r.away_team)
        for r in nxt.itertuples(index=False)
    ]
    mini = SimulatedLeague(
        registry=league.registry,
        true_params=league.true_params,
        matches=df,
        fixtures=fixtures,
        seasons=league.seasons,
        season_registries=dict(league.season_registries),
    )
    mini.odds = simulate_bookmaker_odds(mini, np.random.default_rng(seed))
    return mini


def simulate_serie_d_registry(seed: int = 7, n_teams: int = 18, *, season: str = DEFAULT_SEASON) -> TeamRegistry:
    """Synthetic Serie D registry: ``n_teams`` clubs in each of the configured Serie D gironi (``DA`` .. ``DI``).

    The real Serie D compositions are not known offline (the FootyStats harvester
    initialises them), so tests and demos of the Serie D section use this
    registry: clubs are named ``'Squadra DA 01'`` .. ``'Squadra DI 18'``
    (:data:`SERIE_D_TEAM_PREFIX` + competition code + zero-padded number, unique
    once normalised), with no aliases. ``seed`` shuffles the order of the clubs
    inside each girone, which is the order :func:`round_robin` pairs them in, so
    different seeds give different calendars; the names themselves are fixed.
    ``season`` is the registry label (``'2026_27'`` or ``'2026/27'``), which sets
    the simulated calendar of :func:`simulate_league`. ``ValueError`` when
    ``n_teams < 2`` or when no competition of the ``'Serie D'`` family is configured.
    """
    if int(n_teams) < 2:
        raise ValueError("n_teams must be >= 2")
    gironi = [g for g in Girone if g.family == "Serie D"]
    if not gironi:
        raise ValueError("no competition of family 'Serie D' in config/competitions.toml")
    rng = np.random.default_rng(seed)
    teams_by_code: dict[str, tuple[str, ...]] = {}
    for g in gironi:
        names = [f"{SERIE_D_TEAM_PREFIX} {g.value} {i:02d}" for i in range(1, int(n_teams) + 1)]
        teams_by_code[g.value] = tuple(str(name) for name in rng.permutation(np.array(names, dtype=object)))
    return TeamRegistry.from_teams(str(season).replace("_", "/"), teams_by_code)
